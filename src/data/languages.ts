/**
 * Returns translated string for a given key and language code.
 * Falls back to English if the specific language key is not available.
 */
export function getTranslation(key: string, lang: SupportedLanguage | string = 'en'): string {
  const code = (lang as SupportedLanguage) || 'en';
  if (TRANSLATIONS[key] && TRANSLATIONS[key][code]) {
    return TRANSLATIONS[key][code]!;
  }
  if (TRANSLATIONS[key] && TRANSLATIONS[key]['en']) {
    return TRANSLATIONS[key]['en']!;
  }
  return key;
}

